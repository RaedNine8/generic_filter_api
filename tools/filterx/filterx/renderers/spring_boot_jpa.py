def _render_specifications(package: str) -> str:
    return _package_header(package) + '''import com.fasterxml.jackson.databind.JsonNode;
import jakarta.persistence.criteria.CriteriaBuilder;
import jakarta.persistence.criteria.Expression;
import jakarta.persistence.criteria.From;
import jakarta.persistence.criteria.JoinType;
import jakarta.persistence.criteria.Path;
import jakarta.persistence.criteria.Predicate;
import jakarta.persistence.criteria.Root;
import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.UUID;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.stereotype.Component;

@Component
public final class FilterxSpecifications {
    private final FilterxMetadata metadata;
    public FilterxSpecifications(FilterxMetadata metadata) { this.metadata = metadata; }

    public Specification<Object> condition(JsonNode entity, FilterxRequests.FilterCondition condition) {
        JsonNode field = metadata.field(entity, condition.field());
        boolean supported = false;
        for (JsonNode operation : field.path("operations")) if (condition.operation().equals(operation.asText())) supported = true;
        if (!supported) throw new FilterxRequestException("OPERATION_UNSUPPORTED", "Operation '" + condition.operation() + "' is not valid for '" + condition.field() + "'.");
        return (root, query, cb) -> predicate(root, cb, condition);
    }

    public Specification<Object> tree(JsonNode entity, FilterxRequests.FilterNode node) {
        if (node == null) return Specification.where(null);
        if (node.condition() != null) return condition(entity, node.condition());
        List<FilterxRequests.FilterNode> children = node.children() == null ? List.of() : node.children();
        if (children.isEmpty()) throw new FilterxRequestException("FILTER_TREE_INVALID", "Filter groups require at least one child.");
        Specification<Object> combined = tree(entity, children.get(0));
        for (int index = 1; index < children.size(); index++) {
            combined = "OR".equalsIgnoreCase(node.operator()) ? combined.or(tree(entity, children.get(index))) : combined.and(tree(entity, children.get(index)));
        }
        return combined;
    }

    public Specification<Object> search(JsonNode entity, String search) {
        if (search == null || search.isBlank()) return Specification.where(null);
        return (root, query, cb) -> {
            List<Predicate> predicates = new ArrayList<>();
            for (JsonNode field : entity.path("fields")) {
                if (!"string".equals(field.path("type").asText())) continue;
                predicates.add(cb.like(cb.lower(root.get(field.path("name").asText()).as(String.class)), "%" + escape(search.toLowerCase(Locale.ROOT)) + "%", '\\\\'));
            }
            return predicates.isEmpty() ? cb.conjunction() : cb.or(predicates.toArray(Predicate[]::new));
        };
    }

    public Specification<Object> softDelete(JsonNode entity) {
        JsonNode softDelete = entity.path("soft_delete");
        if (!softDelete.path("respected").asBoolean() || softDelete.path("field").isNull()) return Specification.where(null);
        String field = softDelete.path("field").asText();
        return (root, query, cb) -> field.toLowerCase(Locale.ROOT).contains("deleted") && root.get(field).getJavaType() == Boolean.class
            ? cb.isFalse(root.get(field)) : cb.isNull(root.get(field));
    }

    private Predicate predicate(Root<Object> root, CriteriaBuilder cb, FilterxRequests.FilterCondition condition) {
        Path<?> path = resolve(root, condition.field());
        Object value = List.of("in", "not_in", "between", "is_null", "is_not_null").contains(condition.operation())
            ? null : coerce(path.getJavaType(), condition.value());
        return switch (condition.operation()) {
            case "eq" -> value == null ? cb.isNull(path) : cb.equal(path, value);
            case "ne" -> value == null ? cb.isNotNull(path) : cb.notEqual(path, value);
            case "gt" -> compare(cb, path, value, "gt");
            case "gte" -> compare(cb, path, value, "gte");
            case "lt" -> compare(cb, path, value, "lt");
            case "lte" -> compare(cb, path, value, "lte");
            case "in", "not_in" -> membership(cb, path, condition.value(), "not_in".equals(condition.operation()));
            case "between" -> between(cb, path, condition.value());
            case "is_null" -> cb.isNull(path);
            case "is_not_null" -> cb.isNotNull(path);
            case "like" -> cb.like(path.as(String.class), "%" + escape(String.valueOf(value)) + "%", '\\\\');
            case "ilike" -> cb.like(cb.lower(path.as(String.class)), "%" + escape(String.valueOf(value).toLowerCase(Locale.ROOT)) + "%", '\\\\');
            case "starts_with" -> cb.like(path.as(String.class), escape(String.valueOf(value)) + "%", '\\\\');
            case "ends_with" -> cb.like(path.as(String.class), "%" + escape(String.valueOf(value)), '\\\\');
            default -> throw new FilterxRequestException("OPERATION_UNSUPPORTED", "Unsupported operation '" + condition.operation() + "'.");
        };
    }

    private Path<?> resolve(Root<Object> root, String field) {
        String[] parts = field.split("\\\\.");
        From<?, ?> from = root;
        for (int index = 0; index < parts.length - 1; index++) from = from.join(parts[index], JoinType.LEFT);
        return from.get(parts[parts.length - 1]);
    }

    @SuppressWarnings({"rawtypes", "unchecked"})
    private Predicate compare(CriteriaBuilder cb, Path<?> path, Object value, String operation) {
        if (!(value instanceof Comparable comparable)) throw new FilterxRequestException("VALUE_INVALID", "Comparison requires a comparable value.");
        Expression<? extends Comparable> expression = path.as((Class<? extends Comparable>) value.getClass());
        return switch (operation) {
            case "gt" -> cb.greaterThan(expression, comparable);
            case "gte" -> cb.greaterThanOrEqualTo(expression, comparable);
            case "lt" -> cb.lessThan(expression, comparable);
            default -> cb.lessThanOrEqualTo(expression, comparable);
        };
    }

    private Predicate membership(CriteriaBuilder cb, Path<?> path, JsonNode value, boolean negate) {
        if (value == null || !value.isArray()) throw new FilterxRequestException("VALUE_INVALID", "Membership operations require an array.");
        CriteriaBuilder.In<Object> clause = cb.in(path);
        value.forEach(item -> clause.value(coerce(path.getJavaType(), item)));
        return negate ? cb.not(clause) : clause;
    }

    @SuppressWarnings({"rawtypes", "unchecked"})
    private Predicate between(CriteriaBuilder cb, Path<?> path, JsonNode value) {
        if (value == null || !value.isArray() || value.size() != 2) throw new FilterxRequestException("VALUE_INVALID", "between requires exactly two values.");
        Comparable first = (Comparable) coerce(path.getJavaType(), value.get(0));
        Comparable second = (Comparable) coerce(path.getJavaType(), value.get(1));
        return cb.between((Expression<? extends Comparable>) path, first, second);
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    private Object coerce(Class<?> type, JsonNode value) {
        if (value == null || value.isNull()) return null;
        String text = value.asText();
        try {
            if (type == String.class) return text;
            if (type == Integer.class || type == int.class) return Integer.valueOf(text);
            if (type == Long.class || type == long.class) return Long.valueOf(text);
            if (type == Double.class || type == double.class) return Double.valueOf(text);
            if (type == Float.class || type == float.class) return Float.valueOf(text);
            if (type == BigDecimal.class) return new BigDecimal(text);
            if (type == Boolean.class || type == boolean.class) return Boolean.valueOf(text);
            if (type == UUID.class) return UUID.fromString(text);
            if (type == LocalDate.class) return LocalDate.parse(text);
            if (type == LocalDateTime.class) return LocalDateTime.parse(text);
            if (type == OffsetDateTime.class) return OffsetDateTime.parse(text);
            if (type == Instant.class) return Instant.parse(text);
            if (type.isEnum()) return Enum.valueOf((Class<Enum>) type, text);
            return text;
        } catch (RuntimeException error) {
            throw new FilterxRequestException("VALUE_INVALID", "Value '" + text + "' is invalid for " + type.getSimpleName() + ".");
        }
    }

    private String escape(String value) { return value.replace("\\\\", "\\\\\\\\").replace("%", "\\\\%").replace("_", "\\\\_"); }
}
'''


def _render_query_service(package: str, max_cost: int) -> str:
    return _package_header(package) + f'''import com.fasterxml.jackson.databind.JsonNode;
import jakarta.persistence.EntityManager;
import jakarta.persistence.Tuple;
import jakarta.persistence.criteria.CriteriaBuilder;
import jakarta.persistence.criteria.CriteriaQuery;
import jakarta.persistence.criteria.Order;
import jakarta.persistence.criteria.Path;
import jakarta.persistence.criteria.Predicate;
import jakarta.persistence.criteria.Root;
import jakarta.servlet.http.HttpServletRequest;
import java.beans.PropertyDescriptor;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.BeanWrapperImpl;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
public class FilterxQueryService {{
    private static final Logger LOG = LoggerFactory.getLogger(FilterxQueryService.class);
    private static final int MAX_QUERY_COST = {max_cost};
    private final EntityManager entityManager;
    private final FilterxMetadata metadata;
    private final FilterxSpecifications specifications;
    private final FilterxSecurity.RowLevelSecurity rowSecurity;
    private final FilterxSecurity.FieldVisibility visibility;

    public FilterxQueryService(EntityManager entityManager, FilterxMetadata metadata, FilterxSpecifications specifications,
            FilterxSecurity.RowLevelSecurity rowSecurity, FilterxSecurity.FieldVisibility visibility) {{
        this.entityManager = entityManager;
        this.metadata = metadata;
        this.specifications = specifications;
        this.rowSecurity = rowSecurity;
        this.visibility = visibility;
    }}

    @Transactional(readOnly = true)
    public FilterxRequests.PageResponse query(String requested, FilterxRequests.FilterRequest request, int page, int size,
            String sortBy, String order, String search, String action, HttpServletRequest servletRequest) {{
        JsonNode entity = metadata.entity(requested);
        guardCost(request);
        Object principal = servletRequest.getAttribute(FilterxSecurity.IdentityFilter.PRINCIPAL_ATTRIBUTE);
        Specification<Object> specification = compose(entity, request, search, principal, action, servletRequest);
        Class<Object> type = metadata.entityClass(entity);
        CriteriaBuilder cb = entityManager.getCriteriaBuilder();
        CriteriaQuery<Object> query = cb.createQuery(Object.class);
        Root<Object> root = query.from(type);
        Predicate predicate = specification.toPredicate(root, query, cb);
        query.select(root).where(predicate == null ? cb.conjunction() : predicate).distinct(true);
        query.orderBy(sort(cb, root, entity, sortBy, order));
        List<Object> rows = entityManager.createQuery(query).setFirstResult((page - 1) * size).setMaxResults(size).getResultList();

        CriteriaQuery<Long> countQuery = cb.createQuery(Long.class);
        Root<Object> countRoot = countQuery.from(type);
        Predicate countPredicate = specification.toPredicate(countRoot, countQuery, cb);
        countQuery.select(cb.countDistinct(countRoot)).where(countPredicate == null ? cb.conjunction() : countPredicate);
        long total = entityManager.createQuery(countQuery).getSingleResult();
        List<Map<String, Object>> data = rows.stream().map(row -> project(row, entity, principal, action, servletRequest)).toList();
        int totalPages = total == 0 ? 0 : (int) Math.ceil((double) total / size);
        LOG.info("filterx_query entity={{}} action={{}} page={{}} size={{}} total={{}}", entity.path("name").asText(), action, page, size, total);
        return new FilterxRequests.PageResponse(data, new FilterxRequests.PageMeta(page, size, total, totalPages));
    }}

    @Transactional(readOnly = true)
    public List<FilterxRequests.GroupResult> group(String requested, String groupField, FilterxRequests.FilterRequest request,
            String search, String action, HttpServletRequest servletRequest) {{
        if (groupField.contains(".")) throw new FilterxRequestException("GROUP_FIELD_UNSUPPORTED", "Relationship grouping is not portable.");
        JsonNode entity = metadata.entity(requested);
        metadata.field(entity, groupField);
        guardCost(request);
        Object principal = servletRequest.getAttribute(FilterxSecurity.IdentityFilter.PRINCIPAL_ATTRIBUTE);
        Specification<Object> specification = compose(entity, request, search, principal, action, servletRequest);
        CriteriaBuilder cb = entityManager.getCriteriaBuilder();
        CriteriaQuery<Tuple> query = cb.createTupleQuery();
        Root<Object> root = query.from(metadata.entityClass(entity));
        Path<?> group = root.get(groupField);
        Predicate predicate = specification.toPredicate(root, query, cb);
        query.multiselect(group.alias("key"), cb.count(root).alias("count")).where(predicate == null ? cb.conjunction() : predicate).groupBy(group);
        return entityManager.createQuery(query).getResultList().stream()
            .map(tuple -> new FilterxRequests.GroupResult(tuple.get("key"), ((Number) tuple.get("count")).longValue())).toList();
    }}

    private Specification<Object> compose(JsonNode entity, FilterxRequests.FilterRequest request, String search,
            Object principal, String action, HttpServletRequest servletRequest) {{
        Specification<Object> result = specifications.softDelete(entity).and(specifications.search(entity, search));
        for (FilterxRequests.FilterCondition condition : request.filters()) result = result.and(specifications.condition(entity, condition));
        result = result.and(specifications.tree(entity, request.filter_tree()));
        Specification<Object> security = rowSecurity.specification(principal, entity, action, servletRequest);
        return security == null ? result : result.and(security);
    }}

    private Order sort(CriteriaBuilder cb, Root<Object> root, JsonNode entity, String sortBy, String direction) {{
        String selected = sortBy == null || sortBy.isBlank() ? entity.path("identity").path("primary_keys").path(0).asText() : sortBy;
        if (selected.isBlank()) selected = entity.path("fields").path(0).path("name").asText();
        metadata.field(entity, selected);
        Path<?> path = root;
        for (String part : selected.split("\\\\.")) path = path.get(part);
        return "desc".equalsIgnoreCase(direction) ? cb.desc(path) : cb.asc(path);
    }}

    private Map<String, Object> project(Object row, JsonNode entity, Object principal, String action, HttpServletRequest request) {{
        BeanWrapperImpl wrapper = new BeanWrapperImpl(row);
        Map<String, Object> projected = new LinkedHashMap<>();
        for (String field : metadata.fieldNames(entity)) {{
            if (!visibility.visible(principal, entity, field, action, request) || !wrapper.isReadableProperty(field)) continue;
            projected.put(field, wrapper.getPropertyValue(field));
        }}
        return projected;
    }}

    private void guardCost(FilterxRequests.FilterRequest request) {{
        int cost = request.filters().stream().mapToInt(condition -> 1 + condition.field().split("\\\\.").length).sum() + treeCost(request.filter_tree(), 1);
        if (cost > MAX_QUERY_COST) throw new FilterxRequestException("QUERY_COST_EXCEEDED", "Query cost " + cost + " exceeds limit " + MAX_QUERY_COST + ".");
    }}

    private int treeCost(FilterxRequests.FilterNode node, int depth) {{
        if (node == null) return 0;
        if (node.condition() != null) return depth + node.condition().field().split("\\\\.").length;
        return depth + (node.children() == null ? 0 : node.children().stream().mapToInt(child -> treeCost(child, depth + 1)).sum());
    }}
}}
'''


