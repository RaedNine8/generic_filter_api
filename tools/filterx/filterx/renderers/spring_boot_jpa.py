def _java_type(source_type: str) -> str:
    source = source_type.strip()
    allowed = {
        "java.lang.String": "String", "String": "String",
        "java.lang.Integer": "Integer", "int": "Integer",
        "java.lang.Long": "Long", "long": "Long",
        "java.lang.Double": "Double", "double": "Double",
        "java.lang.Float": "Float", "float": "Float",
        "java.lang.Boolean": "Boolean", "boolean": "Boolean",
        "java.math.BigDecimal": "java.math.BigDecimal",
        "java.time.LocalDate": "java.time.LocalDate",
        "java.time.LocalDateTime": "java.time.LocalDateTime",
        "java.time.OffsetDateTime": "java.time.OffsetDateTime",
        "java.time.Instant": "java.time.Instant",
        "java.util.UUID": "java.util.UUID",
    }
    return allowed.get(source, "Object")


def _render_dtos(package: str, ir: FilterxIR) -> str:
    records: list[str] = []
    for entity in ir.entities:
        components = ", ".join(f"{_java_type(field.source_type)} {field.name}" for field in entity.fields)
        records.append(f"    public record {entity.name}Dto({components}) {{}}")
    body = "\n\n".join(records) or "    public record EmptyDto() {}"
    return _package_header(package) + f'''/** Flat, relationship-free response records. They never serialize JPA associations. */
public final class FilterxDtos {{
    private FilterxDtos() {{}}

{body}
}}
'''


