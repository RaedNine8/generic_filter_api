class SpringBootJPARenderer:
    name = "spring-boot-jpa"
    version = "1.0.0"
    target = RendererTarget.BACKEND

    def _load(self, args: Any) -> tuple[Path, dict[str, Any], FilterxIR]:
        project_root = Path(args.project_root).resolve()
        config_path = Path(args.config).resolve() if args.config else None
        cfg = load_effective_config(project_root, config_path).raw
        ir_path = project_root / cfg["output"].get("ir_file", ".filterx/ir.json")
        if not ir_path.is_file():
            raise ValueError(f"FilterX IR artifact is missing at '{ir_path}'. Run 'filterx scan' first.")
        ir = ir_from_dict(load_json(ir_path))
        if ir.version != "filterx-ir/v1":
            raise ValueError(f"Spring renderer requires filterx-ir/v1, received '{ir.version}'.")
        return project_root, cfg, ir

    def _module_root(self, project_root: Path, spring: Mapping[str, Any]) -> Path:
        configured = str(spring.get("module_path", "."))
        candidate = (project_root / configured).resolve()
        if configured != "." or any((candidate / name).is_file() for name in ("pom.xml", "build.gradle", "build.gradle.kts")):
            if not candidate.is_dir():
                raise ValueError(f"Spring module_path does not exist: '{candidate}'.")
            return candidate
        manifests = sorted({path.parent for pattern in ("pom.xml", "build.gradle", "build.gradle.kts") for path in project_root.glob(f"**/{pattern}")})
        if len(manifests) != 1:
            raise ValueError("Spring module detection is ambiguous. Set backend.spring.module_path to the web/JPA module containing the application class.")
        return manifests[0]

    def _build(self, project_root: Path, spring: Mapping[str, Any]) -> tuple[Path, str, Path, str]:
        module = self._module_root(project_root, spring)
        configured = spring.get("build_tool")
        maven = (module / str(spring.get("pom_file", "pom.xml"))).is_file()
        gradle_candidates = [module / name for name in (str(spring.get("gradle_file")) if spring.get("gradle_file") else "", "build.gradle", "build.gradle.kts") if name]
        gradle_files = list(dict.fromkeys(path for path in gradle_candidates if path.is_file()))
        detected = (["maven"] if maven else []) + (["gradle"] if gradle_files else [])
        if configured:
            detected = [str(configured)]
        if len(detected) != 1:
            raise ValueError("Maven/Gradle detection is ambiguous. Set backend.spring.build_tool and module_path explicitly.")
        tool = detected[0]
        if tool == "maven":
            manifest = module / str(spring.get("pom_file", "pom.xml"))
            if not manifest.is_file(): raise ValueError(f"Maven manifest was not found at '{manifest}'.")
            wrapper = next((path for root in (module, project_root) for name in ("mvnw.cmd", "mvnw") if (path := root / name).is_file()), None)
            command = str(spring.get("maven_command") or wrapper or "mvn")
        else:
            if len(gradle_files) != 1:
                raise ValueError("Gradle Groovy/Kotlin manifest detection is ambiguous. Set backend.spring.gradle_file explicitly.")
            manifest = gradle_files[0]
            wrapper = next((path for root in (module, project_root) for name in ("gradlew.bat", "gradlew") if (path := root / name).is_file()), None)
            command = str(spring.get("gradle_command") or wrapper or "gradle")
        self._require_boot3(manifest, tool)
        return module, tool, manifest, command

    def _require_boot3(self, manifest: Path, tool: str) -> None:
        source = manifest.read_text(encoding="utf-8")
        version: str | None = None
        if tool == "maven":
            root = ET.fromstring(source)
            local = lambda tag: tag.rsplit("}", 1)[-1]
            parent = next((child for child in root if local(child.tag) == "parent"), None)
            if parent is not None:
                values = {local(child.tag): (child.text or "").strip() for child in parent}
                if values.get("groupId") == "org.springframework.boot": version = values.get("version")
            if version is None:
                properties = next((child for child in root if local(child.tag) == "properties"), None)
                if properties is not None:
                    values = {local(child.tag): (child.text or "").strip() for child in properties}
                    version = values.get("spring-boot.version")
        else:
            match = _BOOT_PLUGIN_RE.search(source)
            version = match.group(1) if match else None
        if version is None or not version.startswith("3."):
            raise ValueError(f"Spring Boot 3.x could not be verified in '{manifest}'. FilterX generates Java 17+/jakarta sources only.")

    def _layout(self, project_root: Path, spring: Mapping[str, Any], ir: FilterxIR) -> SpringLayout:
        module, tool, manifest, command = self._build(project_root, spring)
        source_root = (module / str(spring.get("source_root", "src/main/java"))).resolve()
        package = str(spring.get("generated_package", ""))
        if not _JAVA_PACKAGE_RE.fullmatch(package):
            raise ValueError(f"Invalid Java package '{package}' in backend.spring.generated_package.")
        generated_root = source_root.joinpath(*package.split("."))
        application = spring.get("application_class")
        candidates = [path for path in source_root.glob("**/*.java") if _BOOT_APPLICATION_RE.search(path.read_text(encoding="utf-8"))] if source_root.is_dir() else []
        if application:
            application = str(application)
            app_path = source_root.joinpath(*application.split(".")).with_suffix(".java")
            if not app_path.is_file(): raise ValueError(f"Configured Spring application class source was not found: '{app_path}'.")
        elif len(candidates) == 1:
            app_path = candidates[0]
            declaration = _PACKAGE_RE.search(app_path.read_text(encoding="utf-8"))
            if not declaration: raise ValueError(f"Spring application source has no package declaration: '{app_path}'.")
            application = declaration.group(1) + "." + app_path.stem
        else:
            raise ValueError("Spring application class detection is ambiguous. Set backend.spring.application_class explicitly.")
        self._validate_package_path(source_root, app_path)
        app_package = str(application).rsplit(".", 1)[0]
        if package != app_package and not package.startswith(app_package + "."):
            raise ValueError(f"Generated package '{package}' must be inside application component-scan package '{app_package}'.")
        for entity in ir.entities:
            if not _JAVA_PACKAGE_RE.fullmatch(entity.identity.module):
                raise ValueError(f"Entity '{entity.name}' has invalid Java package '{entity.identity.module}' in filterx-ir/v1.")
            entity_path = source_root.joinpath(*entity.identity.module.split("."), f"{entity.name}.java")
            if entity_path.exists(): self._validate_package_path(source_root, entity_path)
        expected = source_root.joinpath(*package.split("."))
        if expected != generated_root:
            raise ValueError("Generated package and directory do not correspond.")
        return SpringLayout(module, source_root, package, generated_root, str(application), tool, manifest, command)

    def _validate_package_path(self, source_root: Path, java_file: Path) -> None:
        declaration = _PACKAGE_RE.search(java_file.read_text(encoding="utf-8"))
        if not declaration: raise ValueError(f"Java source has no package declaration: '{java_file}'.")
        expected = source_root.joinpath(*declaration.group(1).split("."), java_file.name).resolve()
        if expected != java_file.resolve():
            raise ValueError(f"Java package-directory mismatch: '{java_file}' declares '{declaration.group(1)}' but should be at '{expected}'.")

    def _dependencies(self, layout: SpringLayout, spring: Mapping[str, Any]) -> PatchOp:
        managed = [
            ("org.springframework.boot", "spring-boot-starter-web"),
            ("org.springframework.boot", "spring-boot-starter-data-jpa"),
            ("org.springframework.boot", "spring-boot-starter-validation"),
            ("org.springframework.boot", "spring-boot-starter-security"),
        ]
        pinned = [
            ("org.springdoc", "springdoc-openapi-starter-webmvc-ui", str(spring["springdoc_version"])),
            ("io.github.resilience4j", "resilience4j-spring-boot3", str(spring["resilience4j_version"])),
            ("org.apache.poi", "poi-ooxml", str(spring["poi_version"])),
        ]
        path = layout.manifest.relative_to(layout.module_root).as_posix()
        if layout.build_tool == "maven":
            dependencies = [{"group_id": group, "artifact_id": name} for group, name in managed]
            dependencies.extend({"group_id": group, "artifact_id": name, "version": version} for group, name, version in pinned)
            return PatchOp(kind="structured_merge", path=path, owner="host", structured_format="xml", merge={"dependencies": dependencies})
        dependencies = [{"configuration": "implementation", "group": group, "name": name} for group, name in managed]
        dependencies.extend({"configuration": "implementation", "group": group, "name": name, "version": version} for group, name, version in pinned)
        return PatchOp(kind="structured_merge", path=path, owner="host", structured_format="gradle", merge={"dependencies": dependencies})

    def _operations(self, project_root: Path, cfg: Mapping[str, Any], ir: FilterxIR, layout: SpringLayout) -> list[PatchOp]:
        spring = cfg["backend"]["spring"]
        files = {
            "FilterxMetadata.java": _render_metadata(layout.generated_package, ir),
            "FilterxDtos.java": _render_dtos(layout.generated_package, ir),
            "FilterxRequests.java": _render_requests(layout.generated_package),
            "FilterxSecurity.java": _render_security(layout.generated_package),
            "FilterxSpecifications.java": _render_specifications(layout.generated_package),
            "FilterxQueryService.java": _render_query_service(layout.generated_package, int(spring["max_query_cost"])),
            "FilterxExportService.java": _render_export_service(layout.generated_package),
            "FilterxController.java": _render_controller(layout.generated_package, str(cfg["backend"].get("api_prefix", "/api"))),
            "FilterxConfiguration.java": _render_configuration(layout.generated_package, int(spring["rate_limit_per_minute"])),
            "FilterxErrorHandler.java": _render_errors(layout.generated_package),
        }
        operations = [PatchOp(kind="generated_file", path=(layout.generated_root / name).relative_to(layout.module_root).as_posix(), content=content) for name, content in files.items()]
        operations.append(self._dependencies(layout, spring))
        return operations

    def install(self, args: Any) -> int:
        try:
            project_root, cfg, ir = self._load(args)
            spring = cfg["backend"]["spring"]
            layout = self._layout(project_root, spring, ir)
            operations = self._operations(project_root, cfg, ir, layout)
        except (ValueError, ET.ParseError) as exc:
            print(json.dumps({"errors": [{"code": "SPRING_CONFIGURATION_INVALID", "message": str(exc)}]}, indent=2))
            return 2
        result = apply_patch_operations(
            project_root=layout.module_root,
            operations=operations,
            manifest_path=project_root / cfg["safety"]["idempotency_manifest"],
            patch_dir=project_root / cfg["output"]["patch_dir"],
            dry_run=bool(getattr(args, "dry_run", False)),
            check_mode=bool(getattr(args, "check", False)),
            strict_conflict_mode=bool(cfg["safety"].get("strict_conflict_mode", True)),
            description="backend.install.spring-boot-jpa",
        )
        print(json.dumps({"framework": self.name, "dry_run": result.dry_run, "patch_id": result.patch_id, "applied_ops": result.applied_ops, "skipped_ops": result.skipped_ops, "touched_files": result.touched_files, "issues": [vars(issue) for issue in result.issues]}, indent=2))
        return 3 if result.has_conflicts else 0

    def compile_command(self, layout: SpringLayout, spring: Mapping[str, Any]) -> tuple[str, ...]:
        if layout.build_tool == "maven":
            return (layout.command, *map(str, spring.get("maven_args", [])), "-DskipTests", "compile")
        return (layout.command, *map(str, spring.get("gradle_args", [])), "classes", "--no-daemon")

    def validate(self, args: Any) -> int:
        try:
            project_root, cfg, ir = self._load(args)
            spring = cfg["backend"]["spring"]
            layout = self._layout(project_root, spring, ir)
        except (ValueError, ET.ParseError) as exc:
            print(json.dumps({"errors": [{"code": "SPRING_CONFIGURATION_INVALID", "message": str(exc)}]}, indent=2))
            return 4
        required = ("FilterxMetadata.java", "FilterxDtos.java", "FilterxRequests.java", "FilterxSecurity.java", "FilterxSpecifications.java", "FilterxQueryService.java", "FilterxExportService.java", "FilterxController.java", "FilterxConfiguration.java", "FilterxErrorHandler.java")
        errors = [{"code": "SPRING_GENERATED_FILE_MISSING", "path": str(layout.generated_root / name)} for name in required if not (layout.generated_root / name).is_file()]
        command = self.compile_command(layout, spring)
        if not errors:
            try:
                result = subprocess.run(command, cwd=layout.module_root, capture_output=True, text=True, timeout=float(spring["compile_timeout_seconds"]), check=False)
                if result.returncode != 0:
                    errors.append({"code": "SPRING_COMPILE_FAILED", "message": "Generated Spring sources did not compile. Fix the reported host/generated source errors and rerun filterx backend validate.", "command": list(command), "exit_code": result.returncode, "stdout": result.stdout[-8000:], "stderr": result.stderr[-8000:]})
            except FileNotFoundError:
                errors.append({"code": "SPRING_BUILD_TOOL_MISSING", "message": f"Build command '{command[0]}' was not found. Add the project wrapper or install {layout.build_tool}.", "command": list(command)})
            except subprocess.TimeoutExpired:
                errors.append({"code": "SPRING_COMPILE_TIMEOUT", "message": "Host compile verification exceeded backend.spring.compile_timeout_seconds.", "command": list(command)})
        payload = {"errors": errors, "warnings": [], "error_count": len(errors), "warning_count": 0, "compile_command": list(command)}
        print(json.dumps(payload, indent=2))
        return 4 if errors else 0

    def remove(self, args: Any) -> int:
        print(json.dumps({"errors": [{"code": "SPRING_REMOVE_USE_ROLLBACK", "message": "Use filterx rollback with the Spring install patch id so generated sources and parser-backed manifest changes are restored together."}]}, indent=2))
        return 2
